"""项目结构说明生成 — 基于 repo_summary.json 输出 STRUCTURE.md。

纯确定性生成，所有内容均可追溯到 repo_summary.json 中的数据。
"""

from __future__ import annotations

import os
from datetime import datetime, timezone

from reposcope.storage.repo_summary import RepoSummary


def generate_structure_md(summary: RepoSummary) -> str:
    """生成 STRUCTURE.md 的完整 Markdown 文本。

    Args:
        summary: 预分析的 RepoSummary

    Returns:
        STRUCTURE.md 的 Markdown 字符串
    """
    repo_name = os.path.basename(summary.repo_path.rstrip(os.sep)) or "project"
    lines: list[str] = []

    _header(lines, repo_name)
    _overview(lines, summary)
    _entry_points(lines, summary)
    _module_roles(lines, summary)
    _topological_layers(lines, summary)
    _structural_core(lines, summary)
    _circular_deps(lines, summary)
    _key_dependencies(lines, summary)
    _file_inventory(lines, summary)
    _footer(lines)

    return "\n".join(lines)


def save_structure_md(summary: RepoSummary, output_path: str) -> str:
    """生成并保存 STRUCTURE.md 文件。

    Returns:
        写入的文件路径
    """
    content = generate_structure_md(summary)
    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)
    return output_path


